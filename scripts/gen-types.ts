// Spec types from the schema: specs/schema/spec.schema.json → types/spec.d.ts (json-schema-to-typescript).
// The schema stays the one source of truth; the .d.ts is generated, committed, and checked for staleness.
// The schema's `if/then` guards (a field allowed only on some element types, `declared` needs a config source) are
// validation, not shape: they are dropped. An `if/then/else` that picks between two shapes (`source`, a scenario
// `step`) becomes a union of the two.
// Usage: node scripts/gen-types.ts           (writes types/spec.d.ts)
//        node scripts/gen-types.ts --check   (exit 1 if the committed file differs from what the schema gives)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SCHEMA = join(root, 'specs', 'schema', 'spec.schema.json');
const OUT = join(root, 'types', 'spec.d.ts');

/** A JSON Schema node: open JSON. */
type SchemaNode = Record<string, unknown>;

const isEmpty = (x: unknown) => x && typeof x === 'object' && !Array.isArray(x) && Object.keys(x).length === 0;

/** Rewrites conditionals: if/then/else → anyOf [then, else]; if/then without else → dropped. */
function shapeOnly(node: unknown): unknown {
    if (Array.isArray(node)) return node.map(shapeOnly);
    if (!node || typeof node !== 'object') return node;
    const { if: cond, then: yes, else: no, ...rest } = node as SchemaNode;
    const out: SchemaNode = Object.fromEntries(Object.entries(rest).map(([k, v]) => [k, shapeOnly(v)]));
    if (cond !== undefined && yes !== undefined && no !== undefined) out.anyOf = [shapeOnly(yes), shapeOnly(no)];
    return out;
}

/** Drops `$defs` that became empty (pure guards like `only-methods`) and every `allOf` reference to them. */
function dropEmptyDefs(schema: SchemaNode & { $defs?: Record<string, unknown> }): SchemaNode {
    const gone = new Set(Object.entries(schema.$defs ?? {}).filter(([, d]) => isEmpty(d)).map(([k]) => k));
    for (const k of gone) delete schema.$defs![k];
    const walk = (n: unknown): void => {
        if (Array.isArray(n)) return n.forEach(walk);
        if (!n || typeof n !== 'object') return;
        const node = n as SchemaNode & { allOf?: unknown[] };
        if (Array.isArray(node.allOf)) {
            node.allOf = (node.allOf as { $ref?: string }[]).filter((x) => !isEmpty(x) && !(x.$ref && gone.has(x.$ref.replace('#/$defs/', ''))));
            if (!node.allOf.length) delete node.allOf;
        }
        Object.values(node).forEach(walk);
    };
    walk(schema);
    return schema;
}

const BANNER = [
    '// Generated by scripts/gen-types.ts from specs/schema/spec.schema.json — do not edit by hand.',
    '// Regenerate: npm run types. Checked by npm run check:types (fails when stale).',
    '// Shapes the schema does not describe (the merged set, core results) are hand-written in types/core.ts.',
].join('\n');

export async function generate(): Promise<string> {
    const schema = dropEmptyDefs(shapeOnly(JSON.parse(readFileSync(SCHEMA, 'utf8'))) as SchemaNode);
    const ts = await compile(schema as Parameters<typeof compile>[0], 'ArchMapSpecDocument', {
        bannerComment: BANNER,
        additionalProperties: false,
        unreachableDefinitions: true,
        cwd: dirname(SCHEMA),
        style: { singleQuote: true, printWidth: 120, tabWidth: 4 },
    });
    // the generator's "referenced by … via the definition …" notes say nothing the type name does not
    return ts
        .replace(/\n \*\n \* This interface was referenced by `ArchMapSpecDocument`'s JSON-Schema\n \* via the `definition` "[^"]+"\./g, '')
        .replace(/\/\*\*\n \* This interface was referenced by `ArchMapSpecDocument`'s JSON-Schema\n \* via the `definition` "[^"]+"\.\n \*\/\n/g, '');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const ts = await generate();
    if (process.argv.includes('--check')) {
        const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
        if (current !== ts) {
            console.error('check:types: types/spec.d.ts is stale — the schema changed; run `npm run types` and commit the result');
            process.exit(1);
        }
        console.log('check:types: ok — types/spec.d.ts matches specs/schema/spec.schema.json');
    } else {
        writeFileSync(OUT, ts);
        console.log(`types: wrote ${OUT.slice(root.length + 1)} (${ts.split('\n').length} lines)`);
    }
}
